#!/usr/bin/env python3
"""Fake provider for the scripted-orchestration runner (TASK-5 demo/tests).

The runner passes the run context via environment variables:

    HARV_RUN_REQUEST  path to request.json
    HARV_RUN_RESULT   path to write result.json
    HARV_NOTES_ROOT   absolute .notes root (artifacts are notes-relative)

Behaviour is selected with ``--mode``:

    success               write all expected outputs + a valid succeeded result
    invalid-json          write malformed result.json (ResultValidator must fail)
    timeout               sleep past the runner timeout
    artifact-not-declared create the expected output files but declare none
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", default="success")
    parser.add_argument("--sleep", type=float, default=30.0,
                        help="seconds to sleep in timeout mode")
    parser.add_argument("--work", type=float, default=0.0,
                        help="success mode: seconds of simulated work before "
                             "writing the result (used to observe parallel fan-out)")
    args = parser.parse_args()

    request_path = Path(os.environ["HARV_RUN_REQUEST"])
    result_path = Path(os.environ["HARV_RUN_RESULT"])
    notes_root = Path(os.environ["HARV_NOTES_ROOT"])
    request = json.loads(request_path.read_text(encoding="utf-8"))

    if args.mode == "timeout":
        print("fake agent sleeping to trigger timeout...")
        time.sleep(args.sleep)
        return 0

    if args.mode == "invalid-json":
        result_path.write_text("{ this is not valid json", encoding="utf-8")
        print("fake agent wrote invalid result")
        return 0

    if args.mode == "failed":
        # A valid structured result that declares its own failure (no outputs).
        result = {
            "schema_version": 1,
            "run_id": request["run_id"],
            "task_id": request["task_id"],
            "stage_id": request["stage_id"],
            "status": "failed",
            "summary": f"fake run for {request['stage_id']} declared failure",
            "artifacts": [],
            "questions": [],
            "incidents": [],
            "next_action": "retry",
        }
        result_path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n",
                               encoding="utf-8")
        print("fake agent declared failure")
        return 0

    # Simulate work so concurrent fan-out branches actually overlap in time;
    # without this the success path returns in ~40ms and parallelism is
    # indistinguishable from sequential execution.
    if args.work > 0:
        time.sleep(args.work)

    # Map each expected output to a registerable artifact type by extension/name.
    expected = request.get("expected_outputs", [])
    artifacts = []
    for rel in expected:
        target = notes_root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(f"# {rel}\n\nGenerated by fake agent for {request['task_id']}.\n",
                          encoding="utf-8")
        artifacts.append({
            "type": _artifact_type(rel),
            "path": rel,
            "description": f"fake artifact for {request['stage_id']}",
        })
        print(f"fake agent wrote {rel}")

    declared = [] if args.mode == "artifact-not-declared" else artifacts

    result = {
        "schema_version": 1,
        "run_id": request["run_id"],
        "task_id": request["task_id"],
        "stage_id": request["stage_id"],
        "status": "succeeded",
        "summary": f"fake run for {request['stage_id']} ({args.mode})",
        "artifacts": declared,
        "questions": [],
        "incidents": [],
        "next_action": "advance",
    }
    result_path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n",
                           encoding="utf-8")
    return 0


def _artifact_type(rel):
    name = rel.lower()
    if "brief" in name:
        return "brief"
    if "spec" in name:
        return "specification"
    if "memory" in name:
        return "memory"
    if "report" in name:
        return "report"
    if "chat" in name:
        return "chat"
    return "report"


if __name__ == "__main__":
    sys.exit(main())
